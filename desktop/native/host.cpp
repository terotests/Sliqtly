int main(int argc, char** argv) {
  double maxSeconds = -1;
  std::string shotAtEnd, iconOut, scriptFile;
  int startW = 1280, startH = 800;
  for (int i = 1; i < argc; i++) {
    std::string a = argv[i];
    if (a == "--seconds" && i + 1 < argc) maxSeconds = std::atof(argv[++i]);
    else if (a == "--shot" && i + 1 < argc) shotAtEnd = argv[++i];
    else if (a == "--icon" && i + 1 < argc) iconOut = argv[++i];
    else if (a == "--script" && i + 1 < argc) scriptFile = argv[++i];
    else if (a == "--size" && i + 1 < argc) std::sscanf(argv[++i], "%dx%d", &startW, &startH);
  }

  if (SDL_Init(SDL_INIT_VIDEO | SDL_INIT_EVENTS) != 0) {
    std::fprintf(stderr, "sliqtly-editor: SDL_Init: %s\n", SDL_GetError());
    return 1;
  }
  SDL_GL_SetAttribute(SDL_GL_CONTEXT_MAJOR_VERSION, 3);
  SDL_GL_SetAttribute(SDL_GL_CONTEXT_MINOR_VERSION, 3);
  SDL_GL_SetAttribute(SDL_GL_CONTEXT_PROFILE_MASK, SDL_GL_CONTEXT_PROFILE_CORE);
#if defined(__APPLE__)
  SDL_GL_SetAttribute(SDL_GL_CONTEXT_MINOR_VERSION, 2);
  SDL_GL_SetAttribute(SDL_GL_CONTEXT_FLAGS, SDL_GL_CONTEXT_FORWARD_COMPATIBLE_FLAG);
#endif
  SDL_GL_SetAttribute(SDL_GL_STENCIL_SIZE, 8);

  configDir = platformConfigDir();
  app = std::make_shared<EditorApp>();
  app->init(EDITOR_CSS);
  for (int i = 0; i < app->styleErrorCount(); i++) std::fprintf(stderr, "editor.css: %s\n", app->styleErrorAt(i).c_str());
  app->setPlatform(platformName());
  app->setNow(epochMs());

  window = SDL_CreateWindow("Sliqtly Editor", SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED, startW, startH,
                            SDL_WINDOW_OPENGL | SDL_WINDOW_RESIZABLE | SDL_WINDOW_ALLOW_HIGHDPI);
  if (!window) {
    std::fprintf(stderr, "sliqtly-editor: window: %s\n", SDL_GetError());
    return 1;
  }
  SDL_SetWindowMinimumSize(window, 800, 520);
  SDL_GLContext ctx = SDL_GL_CreateContext(window);
  if (!ctx) {
    std::fprintf(stderr, "sliqtly-editor: OpenGL 3.3: %s\n", SDL_GetError());
    return 1;
  }
  SDL_GL_SetSwapInterval(1);
  SDL_StartTextInput();

  Painter painter;
  addFaces(painter);
  std::string err;
  if (!painter.init(err)) {
    std::fprintf(stderr, "sliqtly-editor: %s\n", err.c_str());
    return 1;
  }
  setWindowIcon(paintIcon(painter, 256), 256);
  if (!iconOut.empty()) {
    writePam(iconOut, paintIcon(painter, 1024), 1024, 1024);
    SDL_GL_DeleteContext(ctx);
    SDL_DestroyWindow(window);
    SDL_Quit();
    return 0;
  }

  int winW, winH;
  SDL_GetWindowSize(window, &winW, &winH);
  app->setViewport(winW, winH);
  app->loadSettings(platformReadFile(settingsPath()));
  app->start();
  if (!scriptFile.empty()) app->runScript(platformReadFile(scriptFile));

  Workers workers(4);
  OAuthLoopback signIn;
  SDL_Cursor* arrow = SDL_CreateSystemCursor(SDL_SYSTEM_CURSOR_ARROW);
  SDL_Cursor* hand = SDL_CreateSystemCursor(SDL_SYSTEM_CURSOR_HAND);
  SDL_Cursor* ibeam = SDL_CreateSystemCursor(SDL_SYSTEM_CURSOR_IBEAM);
  std::string cursorNow;

  evg::gl::Target uiTarget, slideTarget, slideFlat;
  EJ viewDoc;
  int viewGen = -1, shownGen = -1, shownSlide = -1;
  double deckW = 1920, deckH = 1080;
  bool force = true;
  std::string pendingShot, title, lastState;
  auto t0 = std::chrono::steady_clock::now();
  long frames = 0;
  double wheelAcc = 0;
  bool leftDown = false;
  const bool mac = std::strcmp(platformName(), "mac") == 0;

  while (!quit) {
    bool busy = workers.pending() > 0 || app->busy() || app->scriptRunning() || signIn.active() || !pendingShot.empty();
    SDL_Event ev;
    bool got = SDL_WaitEventTimeout(&ev, busy ? 8 : 100) != 0;
    while (got) {
      SDL_Keymod km = SDL_GetModState();
      bool mod = mac ? (km & KMOD_GUI) != 0 : (km & KMOD_CTRL) != 0;
      switch (ev.type) {
        case SDL_QUIT: quit = true; break;
        case SDL_WINDOWEVENT:
          if (ev.window.event == SDL_WINDOWEVENT_SIZE_CHANGED || ev.window.event == SDL_WINDOWEVENT_RESIZED) {
            SDL_GetWindowSize(window, &winW, &winH);
            app->setViewport(winW, winH);
          }
          force = true;
          break;
        case SDL_MOUSEMOTION: {
          app->pointerMove(ev.motion.x, ev.motion.y, (ev.motion.state & SDL_BUTTON_LMASK) != 0);
          std::string c = app->cursorAt(ev.motion.x, ev.motion.y);
          if (c != cursorNow) {
            cursorNow = c;
            SDL_SetCursor(c == "text" ? ibeam : c == "pointer" ? hand : arrow);
          }
          break;
        }
        case SDL_MOUSEBUTTONDOWN:
          if (ev.button.button == SDL_BUTTON_LEFT) {
            leftDown = true;
            app->setNow(epochMs());
            app->pointerDown(ev.button.x, ev.button.y, (km & KMOD_SHIFT) != 0);
          }
          break;
        case SDL_MOUSEBUTTONUP:
          if (ev.button.button == SDL_BUTTON_LEFT) {
            leftDown = false;
            app->pointerUp(ev.button.x, ev.button.y);
          }
          break;
        case SDL_MOUSEWHEEL: {
#if SDL_VERSION_ATLEAST(2, 0, 18)
          double dy = ev.wheel.preciseY;
#else
          double dy = ev.wheel.y;
#endif
          if (ev.wheel.direction == SDL_MOUSEWHEEL_FLIPPED) dy = -dy;
          wheelAcc -= dy;
          int lines = (int)wheelAcc;
          if (lines != 0) {
            wheelAcc -= lines;
            int mx, my;
            SDL_GetMouseState(&mx, &my);
            app->wheel(mx, my, lines);
          }
          break;
        }
        case SDL_TEXTINPUT:
          // Cmd / Ctrl + a letter is a shortcut, not text.
          if (!mod) app->typeText(ev.text.text);
          break;
        case SDL_KEYDOWN: {
          SDL_Keycode k = ev.key.keysym.sym;
          const char* name = keyName(k);
          std::string letter;
          if (k >= SDLK_a && k <= SDLK_z) letter = std::string(1, (char)('a' + (k - SDLK_a)));
          if (name) {
            app->key(name, (km & KMOD_SHIFT) != 0, mod, (km & KMOD_ALT) != 0);
          } else if (mod && !letter.empty()) {
            if (letter == "q" && mac) quit = true;
            else app->key(letter, (km & KMOD_SHIFT) != 0, mod, (km & KMOD_ALT) != 0);
          }
          break;
        }
        default: break;
      }
      got = SDL_PollEvent(&ev) != 0;
    }
    (void)leftDown;

    app->setNow(epochMs());
    app->scriptTick();

    // the network
    for (int id = app->takeRequest(); id != 0; id = app->takeRequest()) startRequest(workers, id);
    {
      std::deque<Done> ready;
      std::deque<std::function<void()>> calls;
      {
        std::lock_guard<std::mutex> g(doneLock);
        ready.swap(done);
        calls.swap(mainQueue);
      }
      for (auto& d : ready) app->deliver(d.id, (int)d.status, d.body, d.error);
      for (auto& c : calls) c();
    }
    OAuthLoopback::Result sr;
    if (signIn.take(sr)) {
      if (sr.ok) app->oauthCode(sr.code, signIn.verifier, signIn.redirect);
      else app->oauthFailed(sr.error);
    }

    // what the app asks for
    for (std::string cmd = app->takeCommand(); !cmd.empty(); cmd = app->takeCommand()) {
      std::string arg = app->commandArg();
      if (cmd == "save-settings") {
        if (!platformWritePrivate(settingsPath(), app->settingsJson())) std::fprintf(stderr, "sliqtly-editor: cannot write %s\n", settingsPath().c_str());
      } else if (cmd == "copy") {
        SDL_SetClipboardText(arg.c_str());
      } else if (cmd == "paste") {
        if (char* t = SDL_GetClipboardText()) {
          app->paste(t);
          SDL_free(t);
        }
      } else if (cmd == "open-url") {
        platformOpenUrl(arg);
      } else if (cmd == "oauth") {
        std::string why;
        if (signIn.start(why)) signIn.open(app->oauthAuthorizeUrl(signIn.challenge, signIn.state, signIn.redirect));
        else app->oauthFailed(why);
      } else if (cmd == "fetch-ca") {
        pinCa(workers, arg, app->commandArg2());
      } else if (cmd == "shot") {
        pendingShot = arg;
        force = true;
      } else if (cmd == "log") {
        std::printf("%s\n", arg.c_str());
        std::fflush(stdout);
      } else if (cmd == "fail") {
        std::fprintf(stderr, "script failed: %s\n", arg.c_str());
        scriptFailed = true;
        quit = true;
      } else if (cmd == "quit") {
        quit = true;
      }
    }
    if (debugOn()) {
      std::string st = app->debugState();
      if (st != lastState) {
        std::fprintf(stderr, "state: %s\n", st.c_str());
        lastState = st;
      }
    }
    std::string t = app->windowTitle();
    if (t != title) {
      title = t;
      SDL_SetWindowTitle(window, t.c_str());
    }

    // the preview's slides, when new ones came
    if (app->viewGeneration() != viewGen) {
      viewGen = app->viewGeneration();
      viewDoc = EJ();
      std::string body = app->viewBody();
      if (!body.empty() && evg::json::Parser(body).parse(viewDoc)) {
        if (const EJ* d = viewDoc.get("deck")) {
          deckW = d->numOr("width", 1920);
          deckH = d->numOr("height", 1080);
        }
      }
    }

    double secs = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
    bool last = maxSeconds >= 0 && secs >= maxSeconds && frames > 2;
    bool paint = force || app->needsPaint() || shownGen != viewGen || shownSlide != app->previewSlide() || last;
    if (paint) {
      force = false;
      shownGen = viewGen;
      shownSlide = app->previewSlide();
      EJ list;
      if (!evg::json::Parser(app->displayListJson()).parse(list)) {
        std::fprintf(stderr, "sliqtly-editor: the display list did not parse\n");
        return 1;
      }
      int drawW, drawH;
      SDL_GL_GetDrawableSize(window, &drawW, &drawH);
      SDL_GetWindowSize(window, &winW, &winH);
      uiTarget.ensure(drawW, drawH, 4);
      uiTarget.bind();
      painter.draw(list, {winW, winH, drawW, drawH, (float)secs, nullptr});
      uiTarget.resolve(0);
      // The slide: drawn at the preview's size in its own target, then put in place.
      const EJ* lists = viewDoc.get("lists");
      int slide = app->previewSlide();
      if (app->previewVisible() && lists && slide >= 0 && slide < (int)lists->arr.size()) {
        double sx = (double)drawW / winW, sy = (double)drawH / winH;
        int px = (int)std::lround(app->previewX() * sx), py = (int)std::lround(app->previewY() * sy);
        int pw = (int)std::lround(app->previewW() * sx), ph = (int)std::lround(app->previewH() * sy);
        if (pw > 4 && ph > 4) {
          slideTarget.ensure(pw, ph, 4);
          slideTarget.bind();
          painter.draw(lists->arr[slide], {(int)std::lround(deckW), (int)std::lround(deckH), pw, ph, (float)secs, nullptr});
          slideFlat.ensure(pw, ph, 0);
          slideTarget.resolve(slideFlat.fbo());
          glBindFramebuffer(GL_READ_FRAMEBUFFER, slideFlat.fbo());
          glBindFramebuffer(GL_DRAW_FRAMEBUFFER, 0);
          glBlitFramebuffer(0, 0, pw, ph, px, drawH - (py + ph), px + pw, drawH - py, GL_COLOR_BUFFER_BIT, GL_NEAREST);
          glBindFramebuffer(GL_FRAMEBUFFER, 0);
        }
      }
      if (!pendingShot.empty()) {
        shotWindow(pendingShot, drawW, drawH);
        if (debugOn()) std::fprintf(stderr, "shot: %s (%dx%d)\n", pendingShot.c_str(), drawW, drawH);
        pendingShot.clear();
      }
      if (last && !shotAtEnd.empty()) shotWindow(shotAtEnd, drawW, drawH);
      SDL_GL_SwapWindow(window);
      frames++;
    }
    if (last) break;
  }

  SDL_GL_DeleteContext(ctx);
  SDL_DestroyWindow(window);
  SDL_Quit();
  return scriptFailed ? 3 : 0;
}
