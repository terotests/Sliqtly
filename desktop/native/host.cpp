// does not, and asks the app everything else.
//
//   the window, the pointer, the keys, text input (UTF-8), the clipboard
//   the network      libcurl on worker threads, for the requests the app
//                    queues (takeRequest / deliver); a pinned CA per server
//   the settings     settings.json in the settings folder, readable by the
//                    user only (tokens are in it)
//   signing in       the OAuth loopback (oauth.h) and the system browser
//   the pixels       the app's display list, then the server's display list
