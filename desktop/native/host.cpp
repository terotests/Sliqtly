//                    reports (an offscreen target, blitted into place)
//
//   sliqtly-editor [--script file] [--seconds S --shot out.pam] [--size WxH]
//                  [--icon out.pam]
//
// --script runs the app's scripted steps (EditorApp.runScript: what
// scripts/check-native.mjs drives); "shot <file>" there writes the next
// frame as a PAM image. --icon writes the 1024 px application icon and quits.
// SLIQTLY_DEBUG=1 prints the app's state as it changes; SLIQTLY_EDITOR_CONFIG
// puts the settings elsewhere; SLIQTLY_NO_BROWSER prints the sign-in address
