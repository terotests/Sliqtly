bool debugOn() { return std::getenv("SLIQTLY_DEBUG") != nullptr; }

double epochMs() {
  return (double)std::chrono::duration_cast<std::chrono::milliseconds>(std::chrono::system_clock::now().time_since_epoch()).count();
}

// --- the network: a few worker threads, answers collected for the frame loop ----
struct Job {
  int id = 0;
  std::string method, url, body;
  std::vector<std::string> headers;
  HttpOptions opts;
};
struct Done {
  int id = 0;
  long status = 0;
  std::string body, error;
};

class Workers {
 public:
  explicit Workers(int n) {
    for (int i = 0; i < n; i++) threads_.emplace_back([this] { loop(); });
  }
  ~Workers() {
    {
      std::lock_guard<std::mutex> g(lock_);
      stop_ = true;
    }
    wake_.notify_all();
    for (auto& t : threads_) t.join();
  }
  void submit(std::function<void()> job) {
    {
      std::lock_guard<std::mutex> g(lock_);
      jobs_.push_back(std::move(job));
      pending_++;
    }
    wake_.notify_one();
  }
  int pending() const { return pending_.load(); }

 private:
  void loop() {
    for (;;) {
      std::function<void()> job;
      {
        std::unique_lock<std::mutex> g(lock_);
        wake_.wait(g, [this] { return stop_ || !jobs_.empty(); });
        if (stop_ && jobs_.empty()) return;
        job = std::move(jobs_.front());
        jobs_.pop_front();
      }
      job();
      pending_--;
    }
  }
  std::vector<std::thread> threads_;
  std::deque<std::function<void()>> jobs_;
  std::mutex lock_;
  std::condition_variable wake_;
  bool stop_ = false;
  std::atomic<int> pending_{0};
};

std::mutex doneLock;
std::deque<Done> done;
std::deque<std::function<void()>> mainQueue;  // results that are not HTTP answers (CA pinning)

void postMain(std::function<void()> fn) {
  std::lock_guard<std::mutex> g(doneLock);
  mainQueue.push_back(std::move(fn));
}

std::string caFileFor(const std::string& fp) {
  if (fp.empty()) return "";
  return configDir + "/ca/" + fp + ".pem";
}

std::vector<std::string> splitLines(const std::string& s) {
  std::vector<std::string> out;
  std::stringstream ss(s);
  std::string line;
  while (std::getline(ss, line)) {
    if (!line.empty()) out.push_back(line);
  }
  return out;
}

void startRequest(Workers& workers, int id) {
  Job j;
  j.id = id;
  j.method = app->reqMethod(id);
  j.url = app->reqUrl(id);
  j.body = app->reqBody(id);
  j.headers = splitLines(app->reqHeaders(id));
  j.opts.timeoutMs = app->reqTimeoutMs(id);
  j.opts.insecure = app->reqInsecure(id);
  std::string ca = caFileFor(app->reqCa(id));
  if (!ca.empty() && std::filesystem::exists(ca)) j.opts.caFile = ca;
  if (debugOn()) std::fprintf(stderr, "http: %s %s%s\n", j.method.c_str(), j.url.c_str(), j.opts.caFile.empty() ? "" : " (pinned CA)");
  workers.submit([j] {
    HttpResponse r = httpRequest(j.method, j.url, j.headers, j.body, j.opts);
    std::lock_guard<std::mutex> g(doneLock);
    done.push_back({j.id, r.status, r.body, r.error});
  });
}

// Fetch <server>/ca.crt without verifying (it is what is being verified),
// check its SHA-256 against the fingerprint the user accepted, keep it.
void pinCa(Workers& workers, const std::string& url, const std::string& fingerprint) {
  workers.submit([url, fingerprint] {
    HttpOptions o;
    o.insecure = true;
    o.timeoutMs = 15000;
    HttpResponse r = httpRequest("GET", url, {}, "", o);
    std::string want;
    for (char c : fingerprint) {
      if (c == ':') continue;
      want += (char)std::tolower((unsigned char)c);
    }
    bool ok = false;
    std::string why;
    if (r.status != 200) {
      why = r.status == 0 ? r.error : "HTTP " + std::to_string(r.status);
    } else {
      std::string der = sq::pemFirstCertificateDer(r.body);
      std::string got = der.empty() ? "" : sq::hex(sq::Sha256::digest(der));
      if (der.empty()) {
        why = "the answer is not a PEM certificate";
      } else if (got != want) {
        why = "its fingerprint is " + got + ", not the one accepted";
      } else {
        std::error_code ec;
        std::filesystem::create_directories(configDir + "/ca", ec);
        platformPrivateDir(configDir + "/ca");
        ok = platformWritePrivate(caFileFor(want), r.body);
        if (!ok) why = "cannot write it to " + caFileFor(want);
      }
    }
    postMain([want, ok, why] { app->caResult(want, ok, why); });
  });
}

// --- settings --------------------------------------------------------------------
std::string settingsPath() { return configDir + "/settings.json"; }

// --- text ------------------------------------------------------------------------
std::string fontDir() {
  std::string base;
  if (char* b = SDL_GetBasePath()) {
    base = b;
    SDL_free(b);
  }
  for (std::string dir : {base + "fonts", base + "../Resources/fonts", std::string("fonts")}) {
    if (std::filesystem::exists(dir + "/NotoSans-Regular.ttf")) return dir;
  }
  return base + "fonts";
}

void addFaces(Painter& painter) {
  struct F { const char* family; bool bold, italic; const char* file; };
  const F faces[] = {
      {"Noto Sans", false, false, "NotoSans-Regular.ttf"},
      {"Noto Sans", true, false, "NotoSans-Bold.ttf"},
      {"DejaVu Sans Mono", false, false, "DejaVuSansMono.ttf"},
      {"DejaVu Sans Mono", true, false, "DejaVuSansMono-Bold.ttf"},
      {"Open Sans", false, false, "OpenSans-Regular.ttf"},
      {"Open Sans", true, false, "OpenSans-Bold.ttf"},
      {"Open Sans", false, true, "OpenSans-Italic.ttf"},
      {"Open Sans", true, true, "OpenSans-BoldItalic.ttf"},
  };
  std::string dir = fontDir(), err;
  for (const F& f : faces) {
    if (!painter.text().addFaceFile(f.family, f.bold, f.italic, dir + "/" + f.file, &err)) std::fprintf(stderr, "sliqtly-editor: %s\n", err.c_str());
  }
}

// --- pixels ----------------------------------------------------------------------
void writePam(const std::string& path, const std::vector<unsigned char>& rgbaTopDown, int w, int h) {
  std::ofstream f(path, std::ios::binary);
  f << "P7\nWIDTH " << w << "\nHEIGHT " << h << "\nDEPTH 4\nMAXVAL 255\nTUPLTYPE RGB_ALPHA\nENDHDR\n";
  f.write((const char*)rgbaTopDown.data(), (std::streamsize)rgbaTopDown.size());
}

// The window's framebuffer as it is now, top row first.
void shotWindow(const std::string& path, int w, int h) {
  std::vector<unsigned char> rgba((size_t)w * h * 4), flipped((size_t)w * h * 4);
  glBindFramebuffer(GL_READ_FRAMEBUFFER, 0);
  glReadPixels(0, 0, w, h, GL_RGBA, GL_UNSIGNED_BYTE, rgba.data());
  for (int y = 0; y < h; y++) std::memcpy(&flipped[(size_t)y * w * 4], &rgba[(size_t)(h - 1 - y) * w * 4], (size_t)w * 4);
  for (size_t i = 3; i < flipped.size(); i += 4) flipped[i] = 255;
  writePam(path, flipped, w, h);
}

// The application icon, `size` px, straight alpha, top row first.
std::vector<unsigned char> paintIcon(Painter& painter, int size) {
  EJ list;
  evg::json::Parser(app->iconDisplayListJson((double)size)).parse(list);
  evg::gl::Target target;
  target.ensure(size, size, 4);
  target.bind();
  painter.draw(list, {size, size, size, size, 0.f, nullptr});
  std::vector<unsigned char> px = target.readPixels();
  for (size_t i = 0; i + 3 < px.size(); i += 4) {
    unsigned a = px[i + 3];
    for (int c = 0; c < 3; c++) px[i + c] = a ? (unsigned char)std::min(255u, px[i + c] * 255u / a) : 0;
  }
  return px;
}

void setWindowIcon(const std::vector<unsigned char>& rgba, int size) {
  SDL_Surface* s = SDL_CreateRGBSurfaceWithFormat(0, size, size, 32, SDL_PIXELFORMAT_RGBA32);
  if (!s) return;
  SDL_LockSurface(s);
  for (int y = 0; y < size; y++) std::memcpy((Uint8*)s->pixels + (size_t)y * s->pitch, &rgba[(size_t)y * size * 4], (size_t)size * 4);
  SDL_UnlockSurface(s);
  SDL_SetWindowIcon(window, s);
  SDL_FreeSurface(s);
}

const char* keyName(SDL_Keycode k) {
  switch (k) {
    case SDLK_LEFT: return "Left";
    case SDLK_RIGHT: return "Right";
    case SDLK_UP: return "Up";
    case SDLK_DOWN: return "Down";
    case SDLK_HOME: return "Home";
    case SDLK_END: return "End";
    case SDLK_PAGEUP: return "PageUp";
    case SDLK_PAGEDOWN: return "PageDown";
    case SDLK_RETURN:
    case SDLK_KP_ENTER: return "Enter";
    case SDLK_BACKSPACE: return "Backspace";
    case SDLK_DELETE: return "Delete";
    case SDLK_TAB: return "Tab";
    case SDLK_ESCAPE: return "Escape";
    case SDLK_F5: return "F5";
    default: return nullptr;
  }
}

