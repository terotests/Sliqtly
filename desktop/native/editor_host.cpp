// Sliqtly, native: the browser editor's own app (src/PresApp.rgr with EVGUI,
// compiled to C++ by Ranger) in an SDL2 window, painted by EVG's native
// painter. web/main.js is the host it mirrors: this file does for a window
// what that file does for a page, in the same order, and asks the app
// everything else.
//
//   sliqtly-native [deck.md] [--res DIR] [--size WxH] [--shot out.pam]
//                  [--script steps.txt]
//
// --res is the folder with pres.css, the themes, the chrome stylesheets and
// the fonts (the build puts one beside the binary). --shot paints one frame
// (after --script, if any) into out.pam and quits: what the headless check
// drives. Script lines: "click x y", "type text", "key name", "wheel x y dx dy
// precise", "save".
//
// COORDINATES. The app works in window points, like CSS pixels: SDL's mouse
// and wheel positions are points too, so they go to the app unchanged. The
// framebuffer is in pixels (a Retina window has twice as many); only the
// painter sees those, through Frame::drawW/drawH. Mixing the two is the
// classic "the click lands beside the button" bug, so pointToApp() is the
// one conversion and it is the identity.
//
// SCROLLING. Wheels, trackpads and their glide go through PresScrollInput
// (src/PresScrollInput.rgr): the user's natural-scrolling setting is kept
// (SDL's FLIPPED flag is not applied), and a touchpad that leaves moving
// glides on where the platform sends no momentum of its own.

